function render(item) {
  const [type, a, b] = item;
  if (type === "title")
    return new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 200, after: 60 },
      children: [ new TextRun({ text: a, bold: true, size: 52, color: "C2410C", font: FONT }) ] });
  if (type === "subtitle")
    return new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 300 },
      children: [ new TextRun({ text: a, size: 24, color: "6B7280", font: FONT }) ] });
  if (type === "h1")
    return new Paragraph({ heading: HeadingLevel.HEADING_1, spacing: { before: 300, after: 120 },
      children: [ new TextRun({ text: a, bold: true, size: 30, color: "1F4E79", font: FONT }) ],
      border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: "DDE3EA", space: 4 } } });
  if (type === "h2")
    return new Paragraph({ heading: HeadingLevel.HEADING_2, spacing: { before: 160, after: 60 },
      children: [ new TextRun({ text: a, bold: true, size: 24, color: "2E74B5", font: FONT }) ] });
  if (type === "p")
    return new Paragraph({ spacing: { after: 100, line: 300 },
      children: [ new TextRun({ text: a, size: 22, font: FONT }) ] });
  if (type === "b")
    return new Paragraph({ numbering: { reference: "bul", level: 0 }, spacing: { after: 60, line: 290 },
      children: [ new TextRun({ text: a, size: 22, font: FONT }) ] });
  if (type === "s")
    return new Paragraph({ spacing: { after: 80, line: 290 }, indent: { left: 200 },
      children: [ new TextRun({ text: a + ". ", bold: true, size: 22, color: "C2410C", font: FONT }),
                  new TextRun({ text: b, size: 22, font: FONT }) ] });
  if (type === "t")
    return new Paragraph({ spacing: { before: 40, after: 120, line: 290 }, indent: { left: 120 },
      shading: { fill: "FFF7ED" },
      children: [ new TextRun({ text: "💡 팁  ", bold: true, size: 21, color: "B45309", font: FONT }),
                  new TextRun({ text: a, italics: true, size: 21, color: "7C4A03", font: FONT }) ] });
  if (type === "q")
    return new Paragraph({ spacing: { before: 120, after: 20, line: 290 },
      children: [ new TextRun({ text: "Q. ", bold: true, size: 22, color: "1F4E79", font: FONT }),
                  new TextRun({ text: a, bold: true, size: 22, font: FONT }) ] });
  if (type === "a")
    return new Paragraph({ spacing: { after: 60, line: 290 }, indent: { left: 200 },
      children: [ new TextRun({ text: "A. ", bold: true, size: 22, color: "10B981", font: FONT }),
                  new TextRun({ text: a, size: 22, font: FONT }) ] });
  return new Paragraph({ children: [ new TextRun({ text: a || "", font: FONT }) ] });
}

const doc = new Document({
  numbering: { config: [ { reference: "bul", levels: [ { level: 0, format: LevelFormat.BULLET, text: "•",
    alignment: AlignmentType.LEFT, style: { paragraph: { indent: { left: 460, hanging: 200 } } } } ] } ] },
  styles: { default: { document: { run: { font: FONT, size: 22 } } } },
  sections: [ { properties: { page: { margin: { top: 1000, bottom: 1000, left: 1100, right: 1100 } } },
    children: B.map(render) } ]
});

Packer.toBuffer(doc).then((buf) => {
  fs.writeFileSync("C:\\CallRadar\\콜레이더_사용설명서.docx", buf);
  console.log("DOCX_WRITTEN");
});
